-- =====================================================================
-- Model-drift monitoring framework (repeatable, SQL-only)
-- =====================================================================
-- Run daily against the scored-transactions table `fraud_scores`
--   (txn_id, score_date, fraud_score, is_fraud [when labeled], plus the
--   35 feature columns from fraud_feature_mart).
--
-- Three check families:
--   A. score-band distribution drift vs baseline (PSI)
--   B. per-feature drift (PSI on binned features)
--   C. alert-volume checks (review queue / decline counts vs baseline)
--
-- Alerting convention used by the Tableau dashboard:
--   PSI < 0.10  -> stable (green)
--   0.10-0.25   -> watch, investigate (amber)
--   PSI > 0.25  -> significant shift, retrain candidate (red)
-- =====================================================================

-- 0) parameters: set these per run -----------------------------------------
-- SET baseline_start = DATE '2026-01-01';   -- first scored day used as baseline
-- SET baseline_end   = DATE '2026-01-07';
-- SET monitor_date   = CURRENT_DATE;

-- A) score-band PSI vs baseline ---------------------------------------------
-- Score bands mirror the 3-tier strategy cutoffs (approve / review / decline).
WITH bands AS (
  SELECT
    score_date,
    CASE
      WHEN fraud_score < 0.01 THEN 'b1_<0.01'
      WHEN fraud_score < 0.05 THEN 'b2_0.01-0.05'
      WHEN fraud_score < 0.20 THEN 'b3_0.05-0.20'
      WHEN fraud_score < 0.50 THEN 'b4_0.20-0.50'
      WHEN fraud_score < :review_cutoff THEN 'b5_0.50-review'
      WHEN fraud_score < :decline_cutoff THEN 'b6_review'
      ELSE 'b7_decline'
    END AS score_band
  FROM fraud_scores
  WHERE score_date BETWEEN :baseline_start AND :monitor_date
),
mix AS (
  SELECT
    score_band,
    SUM(CASE WHEN score_date BETWEEN :baseline_start AND :baseline_end
             THEN 1.0 ELSE 0.0 END)
      / NULLIF(SUM(CASE WHEN score_date BETWEEN :baseline_start AND :baseline_end
                        THEN 1.0 ELSE 0.0 END) OVER (), 0) AS pct_expected,
    SUM(CASE WHEN score_date = :monitor_date THEN 1.0 ELSE 0.0 END)
      / NULLIF(SUM(CASE WHEN score_date = :monitor_date THEN 1.0 ELSE 0.0 END) OVER (), 0)
      AS pct_actual
  FROM bands
  GROUP BY score_band
)
SELECT
  :monitor_date AS monitor_date,
  SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) AS psi_score_bands,
  CASE
    WHEN SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) > 0.25
      THEN 'RED: significant score shift'
    WHEN SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) > 0.10
      THEN 'AMBER: watch'
    ELSE 'GREEN: stable'
  END AS drift_status
FROM mix;

-- B) per-feature drift: PSI on decile bins frozen at baseline ---------------
-- Template: repeat per feature (35 features). Bin edges are computed ONCE on
-- the baseline window and stored in `feature_bin_edges(feature, bin, lo, hi)`.
-- Example for one feature (amount):
WITH binned AS (
  SELECT
    CASE WHEN f.score_date BETWEEN :baseline_start AND :baseline_end THEN 'base'
         WHEN f.score_date = :monitor_date THEN 'curr' END AS period,
    e.bin AS bin
  FROM fraud_scores f
  JOIN feature_bin_edges e
    ON e.feature = 'amount'
   AND f.amount >= e.lo AND f.amount < e.hi
  WHERE f.score_date BETWEEN :baseline_start AND :baseline_end
     OR f.score_date = :monitor_date
),
mix AS (
  SELECT bin,
         SUM(CASE WHEN period = 'base' THEN 1.0 ELSE 0 END)
           / SUM(SUM(CASE WHEN period = 'base' THEN 1.0 ELSE 0 END)) OVER ()
           AS pct_expected,
         SUM(CASE WHEN period = 'curr' THEN 1.0 ELSE 0 END)
           / NULLIF(SUM(SUM(CASE WHEN period = 'curr' THEN 1.0 ELSE 0 END)) OVER (), 0)
           AS pct_actual
  FROM binned GROUP BY bin
)
SELECT 'amount' AS feature,
       SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) AS psi,
       CASE WHEN SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) > 0.25
            THEN 'RED' WHEN SUM((pct_actual - pct_expected) * LN(pct_actual / pct_expected)) > 0.10
            THEN 'AMBER' ELSE 'GREEN' END AS drift_status
FROM mix;
-- NOTE: the full 35-feature sweep is generated by
--   scripts/sweep_feature_psi.py (renders one UNION ALL query from the
--   feature list), keeping this framework repeatable.

-- C) alert-volume checks ------------------------------------------------------
-- Compare today's review-queue and decline counts (and precision when labels
-- have landed) against the trailing-7-day mean +/- 3 sigma.
WITH daily AS (
  SELECT
    score_date,
    SUM(CASE WHEN fraud_score >= :review_cutoff
              AND fraud_score < :decline_cutoff THEN 1 ELSE 0 END) AS n_review,
    SUM(CASE WHEN fraud_score >= :decline_cutoff THEN 1 ELSE 0 END) AS n_decline,
    AVG(CASE WHEN fraud_score >= :review_cutoff THEN is_fraud END) AS review_precision_labeled
  FROM fraud_scores
  WHERE score_date BETWEEN DATE_ADD(:monitor_date, -8) AND :monitor_date
  GROUP BY score_date
),
stats AS (
  SELECT AVG(n_review) AS mu_r, STDDEV_SAMP(n_review) AS sd_r,
         AVG(n_decline) AS mu_d, STDDEV_SAMP(n_decline) AS sd_d
  FROM daily WHERE score_date < :monitor_date
)
SELECT
  d.score_date, d.n_review, d.n_decline,
  ROUND(d.review_precision_labeled, 4) AS review_precision_labeled,
  CASE WHEN ABS(d.n_review - s.mu_r) > 3 * s.sd_r THEN 'RED: review volume anomaly'
       WHEN ABS(d.n_review - s.mu_r) > 2 * s.sd_r THEN 'AMBER: review volume elevated'
       ELSE 'GREEN' END AS review_volume_status,
  CASE WHEN ABS(d.n_decline - s.mu_d) > 3 * s.sd_d THEN 'RED: decline volume anomaly'
       WHEN ABS(d.n_decline - s.mu_d) > 2 * s.sd_d THEN 'AMBER: decline volume elevated'
       ELSE 'GREEN' END AS decline_volume_status
FROM daily d CROSS JOIN stats s
WHERE d.score_date = :monitor_date;
